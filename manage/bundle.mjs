// Packs the app files (manage/public) into manage/src/assets.js, which the Worker serves.
// Run before every deploy (the workflow does it): node manage/bundle.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, 'public');
const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8', '.json': 'application/json; charset=utf-8',
  '.png': 'image/png', '.svg': 'image/svg+xml', '.woff': 'font/woff', '.woff2': 'font/woff2', '.txt': 'text/plain; charset=utf-8',
};

const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) { walk(full); continue; }
    const type = TYPES[extname(name)];
    if (!type) continue;                                  // e.g. _headers: the Worker sets the headers itself
    const bytes = readFileSync(full);
    const path = '/' + relative(root, full).split('\\').join('/');
    files[path] = [type, bytes.toString('base64'), '"' + createHash('sha256').update(bytes).digest('hex').slice(0, 20) + '"'];
  }
})(root);

writeFileSync(join(here, 'src', 'assets.js'),
  '// Generated by manage/bundle.mjs from manage/public. Do not edit.\nexport default ' + JSON.stringify(files) + ';\n');
console.log(`assets.js: ${Object.keys(files).length} files`);
